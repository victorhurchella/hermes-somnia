"""Where insights are written: the proposal in the nightly inbox note, the living note of approved
insights, and the few entries Somnia keeps in USER.md (a pointer, and insights about the agent's answers).

Rules that keep this safe:
* a proposal changes nothing but the inbox note; the living note and USER.md only see approved insights;
* the living note is generated from the store on every change, and Somnia refuses to write a file it
  did not create (the ``somnia: insights`` frontmatter marker);
* USER.md entries are additions only: no room means a warning, never an eviction.
"""

