def _lang(settings) -> str:
    return "pt-BR" if str(getattr(settings, "vault_language", "en")).lower().startswith("pt") else "en"


def _t(settings, key: str):
    return TEXT[_lang(settings)][key]


def _vault(settings) -> Optional[Path]:
    vault = settings.resolved_vault() if settings.wants_vault else None
    return vault if vault is not None and vault.is_dir() else None


# --- proposals in the nightly inbox note ---

def proposal_block(settings, j: Judgment, occ: list[dict]) -> list[str]:
    days = len({o["day"] for o in occ})
    relation = _t(settings, j.relation if j.relation in ("new", "refines") else "new")
    if j.relation == "refines" and j.delta:
        relation += f" ({j.delta})"
    lines = [f"- [ ] **{j.title}** — {j.criterion}"]
    if j.user_version:
        lines.append(f"  - {_t(settings, 'how')}: {j.user_version}")
    lines.append(f"  - {_t(settings, 'rule')}: {j.rule}")
    lines.append(f"  - {_t(settings, 'occasions')}: {len(occ)} {_t(settings, 'on_days').format(d=days)} · "
                 f"{_t(settings, 'area')}: {_t(settings, 'areas')[j.area].lower()} · {relation} · key: `{j.key}`")
    lines += [f"  - {o['day']} · {o['context']}: \"{o['quote']}\"" for o in occ]
    return lines


def write_proposals(settings, store: Store, proposals: list[Judgment], day: str, *, dry_run: bool,
                    stamp: str = "", sweep_header: bool = True) -> tuple[Optional[Path], list[str]]:
    """Append tonight's proposals to ``<vault_folder>/<day>.md``. Without a vault there is no note: the
    desktop page and the morning report carry the proposals."""
    if not proposals or _vault(settings) is None:
        return None, []
    folder = vault_dir(settings)
    note = folder / f"{day}.md"
    lines = [] if note.exists() else vault_note_header(day, settings)
    if sweep_header:
        lines += [f"## {_t(settings, 'sweep')} {stamp}".rstrip(), ""]
    lines.append(f"### {_t(settings, 'insights')}")
    for j in proposals:
        lines += proposal_block(settings, j, occasions(store, j.key))
    lines.append("")
    if dry_run:
        return note, lines
    folder.mkdir(parents=True, exist_ok=True)
    with open(note, "a", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    for j in proposals:
        j.note = str(note)
        store.save_judgment(j)
    return note, lines


_KEY_RE = re.compile(r"key: `(insight:[0-9a-f]+)`")


def read_ticks(settings, store: Store, warnings: Optional[list] = None) -> list[str]:
    """Keys of proposals whose checkbox the user ticked. Only notes that still hold a proposed insight are
    read, and the block is found by its ``key:`` marker, so an edit of the visible text does not matter."""
    proposed = {j.key: j for j in store.judgments("proposed")}
    ticked: list[str] = []
    for note in sorted({j.note for j in proposed.values() if j.note}):
        path = Path(note)
        if not path.exists():
            continue
        head = None
        for line in path.read_text(encoding="utf-8", errors="ignore").split("\n"):
            if line.startswith("- "):
                head = line
                continue
            match = _KEY_RE.search(line) if line.startswith("  ") else None
            if not match or head is None or not re.match(r"- \[[xX]\]", head):
                continue
            key = match.group(1)
            if key in proposed:
                if key not in ticked:
                    ticked.append(key)
            elif store.judgment(key) is None and warnings is not None:
                warnings.append(f"insights: a ticked proposal in {path.name} is unknown to the store ({key})")
    return ticked


# --- the living note ---

def living_note_path(settings, base: Path) -> Path:
    vault = _vault(settings)
    if vault is None:
        return Path(base) / "insights.md"
    rel = (getattr(settings, "insights_note", "") or "").strip() or f"{settings.vault_folder}/insights.md"
    path = (vault / rel).resolve()
    if not _inside(path, vault) or path == vault.resolve():
        raise RuntimeError("insights_note must be a file inside the vault")
    return path


def _has_marker(path: Path) -> bool:
    text = path.read_text(encoding="utf-8", errors="ignore")
    if not text.startswith("---"):
        return False
    end = text.find("\n---", 3)
    return end != -1 and MARKER in text[:end]


def _day(ts: Optional[float]) -> str:
    return datetime.fromtimestamp(ts or 0).strftime("%Y-%m-%d")


def _note_link(settings, j: Judgment) -> str:
    vault = _vault(settings)
    if vault is None or not j.note:
        return ""
    try:
        rel = Path(j.note).resolve().relative_to(vault.resolve())
    except ValueError:
        return ""
    return f"[[{rel.with_suffix('').as_posix()}]]"


def render_living_note(settings, store: Store) -> str:
    approved = store.judgments("approved")
    note_type = (getattr(settings, "vault_note_type", "") or "inbox").strip()
    tags = [str(t).strip() for t in (getattr(settings, "vault_note_tags", None) or ["somnia"]) if str(t).strip()]
    stamps = [j.decided_at or j.proposed_at for j in approved]
    lines = ["---", f"title: {_t(settings, 'title')}"]
    if stamps:
        lines += [f"created: {_day(min(stamps))}", f"updated: {_day(max(stamps))}"]
    lines += [f"type: {note_type}", f"tags: [{', '.join(tags)}]", f"source: {_t(settings, 'source')}", MARKER, "---",
              f"# {_t(settings, 'title')}", "", _t(settings, "generated"), ""]
    for area in AREAS:
        group = [j for j in approved if j.area == area]
        if not group:
            continue
        lines += [f"## {_t(settings, 'areas')[area]}", ""]
        for j in group:
            occ = occasions(store, j.key)
            days = sorted(o["day"] for o in occ)
            span = _t(settings, "span").format(n=len(occ), a=days[0], b=days[-1]) if occ else _t(settings, "none")
            tail = " · ".join(x for x in (span, _note_link(settings, j), f"key: `{j.key}`") if x)
            lines += [f"### {j.title}", j.criterion, f"**{_t(settings, 'rule_bold')}:** {j.rule}", tail, ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def write_living_note(settings, store: Store, base: Path) -> Path:
    path = living_note_path(settings, base)
    if path.exists() and not _has_marker(path):
        raise RuntimeError(f"{path} was not created by Somnia (no '{MARKER}' in its frontmatter); "
                           "point insights_note at another file")
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".somnia-tmp")
    tmp.write_text(render_living_note(settings, store), encoding="utf-8")
    os.replace(tmp, path)
    return path


def known_text(settings) -> str:
    """The notes where the user already wrote their principles down (read only)."""
    vault = _vault(settings)
    if vault is None:
        return ""
    parts = []
    for rel in getattr(settings, "insights_known_notes", None) or []:
        path = (vault / str(rel)).resolve()
        if _inside(path, vault) and path.is_file():
            parts.append(f"## {rel}\n" + path.read_text(encoding="utf-8", errors="ignore")[:KNOWN_NOTE_CHARS])
    return "\n\n".join(parts)


# --- USER.md: pointer + inline rules ---

def _user_ready(settings, backend: Optional[MemoryBackend]) -> Optional[str]:
    if backend is None:
        return "USER.md is not available"
    if "user" not in (getattr(settings, "targets", None) or []):
        return "targets excludes user"
    return None


def _add_user_entry(store: Store, backend: MemoryBackend, text: str, key: Optional[str], klass: str,
                    what: str) -> Optional[str]:
    entries = backend.entries("user")
    if text in entries:
        store.own(sha1_12(text), "user", text, key, None, klass=klass)
        return None
    if size_of(entries + [text]) > backend.limit("user"):
        return f"skipped: USER.md has no room for {what}"
    out = backend.apply("user", [{"action": "add", "content": text}])
    if not out.get("success"):
        return f"skipped: USER.md refused {what} ({str(out.get('error') or out)[:120]})"
    store.own(sha1_12(text), "user", text, key, None, klass=klass)
    return None


def ensure_pointer(store: Store, settings, backend: Optional[MemoryBackend], note: Path) -> Optional[str]:
    """One USER.md entry that tells the agent to read the living note. Returns a warning line, or None."""
    if not getattr(settings, "insights_pointer", True):
        return None
    blocked = _user_ready(settings, backend)
    if blocked:
        return f"insights pointer skipped: {blocked}"
    assert backend is not None
    text = POINTER_TEXT[_lang(settings)].format(path=str(note))
    entries = backend.entries("user")
    for row in [r for r in store.owned("user").values() if r.get("class") == "pointer"]:
        if row["text"] == text and text in entries:
            return None
        if row["text"] in entries:  # the note moved: keep one pointer, with the current path
            out = backend.apply("user", [{"action": "replace", "old_text": row["text"], "content": text}])
            if not out.get("success"):
                return f"insights pointer not updated ({str(out.get('error') or out)[:120]})"
            store.disown(row["entry_hash"])
            store.own(sha1_12(text), "user", text, None, None, klass="pointer")
            return None
        store.disown(row["entry_hash"])  # removed by hand: add it again below
    warning = _add_user_entry(store, backend, text, None, "pointer", "the insights pointer")
    return f"insights pointer {warning}" if warning else None


def sync_inline(store: Store, settings, backend: Optional[MemoryBackend], j: Judgment) -> tuple[bool, Optional[str]]:
    """Copy an approved insight about the agent's answers into USER.md as its one-line rule. First come:
    a full quota or a full file leaves it in the living note only."""
    if j.area != "responses" or j.inline_hash or len(j.rule) > INLINE_CHARS:
        return bool(j.inline_hash), None
    taken = sum(1 for other in store.judgments("approved") if other.inline_hash)
    if taken >= int(getattr(settings, "insights_inline_max", 3)):
        return False, None
    blocked = _user_ready(settings, backend)
    if blocked:
        return False, f"insight not copied to USER.md: {blocked}"
    assert backend is not None
    warning = _add_user_entry(store, backend, j.rule, j.key, "inline", "this insight")
    if warning:
        return False, f"insight {warning}"
    j.inline_hash = sha1_12(j.rule)
    store.save_judgment(j)
    return True, None


def _remove_inline(store: Store, backend: Optional[MemoryBackend], j: Judgment) -> None:
    if not j.inline_hash:
        return
    row = store.owned("user").get(j.inline_hash)
    if row and backend is not None and row["text"] in backend.entries("user"):
        backend.apply("user", [{"action": "remove", "old_text": row["text"]}])
    store.disown(j.inline_hash)
    j.inline_hash = None


# --- approve / forget ---

def approve(store: Store, settings, backend: Optional[MemoryBackend], key: str, now: float, base: Path) -> dict:
    """Make an insight count: living note, pointer, and USER.md when it is about the agent's answers.
    Raises KeyError for an unknown key and RuntimeError when the living note cannot be written (the
    insight then stays as it was)."""
    j = store.judgment(key)
    if j is None:
        raise KeyError(key)
    before = (j.status, j.decided_at)
    j.status, j.decided_at = "approved", now
    store.save_judgment(j)
    try:
        note = write_living_note(settings, store, base)
    except Exception:
        j.status, j.decided_at = before
        store.save_judgment(j)
        raise
    warnings = [w for w in [ensure_pointer(store, settings, backend, note)] if w]
    inlined, warning = sync_inline(store, settings, backend, j)
    if warning:
        warnings.append(warning)
    return {"ok": True, "key": key, "note": str(note), "inlined": inlined, "warnings": warnings}


def forget(store: Store, settings, backend: Optional[MemoryBackend], key: str, now: float, base: Path) -> dict:
    """Reject an insight for good. Returns the proposal block cut from its inbox note (if any), so the
    caller can keep it for ``unforget``."""
    j = store.judgment(key)
    if j is None:
        raise KeyError(key)
    was_approved = j.status == "approved"
    _remove_inline(store, backend, j)
    j.status, j.decided_at = "rejected", now
    store.save_judgment(j)
    block = remove_from_vault(Path(j.note), key) if j.note else None
    if was_approved:
        write_living_note(settings, store, base)
    return {"ok": True, "key": key, "was_approved": was_approved, "note": j.note, "block": block}


def unforget(store: Store, key: str) -> bool:
    j = store.judgment(key)
    if j is None or j.status != "rejected":
        return False
    j.status, j.decided_at = "proposed", None
    store.save_judgment(j)
    return True
